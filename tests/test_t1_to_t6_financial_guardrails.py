"""T1-T6 financial guardrail tests.

T1/T2/T4/T6 unit behavior is covered by the focused test modules. T3 (persisted
expiry) and T5 (atomic one-time consumption) use a separately allowlisted Supabase
test project only. They are explicitly skipped unless all isolation controls exist.
"""
from __future__ import annotations

import concurrent.futures
import json
import os
import re
import urllib.error
import urllib.parse
import urllib.request
import uuid
from datetime import datetime, timedelta, timezone

import pytest


PRODUCTION_PROJECT_REF = "nruxwnfiwxeomeqalgat"


def _isolated_supabase():
    if os.getenv("VEROX_RUN_SUPABASE_FINANCIAL_INTEGRATION") != "1":
        pytest.skip("Supabase financial integration tests not explicitly enabled")
    base_url = os.getenv("SUPABASE_TEST_URL", "").strip().rstrip("/")
    service_key = os.getenv("SUPABASE_TEST_SERVICE_KEY", "").strip()
    allowlist = {
        item.strip()
        for item in os.getenv("SUPABASE_TEST_PROJECT_REF_ALLOWLIST", "").split(",")
        if item.strip()
    }
    match = re.fullmatch(r"https://([a-z0-9-]+)\.supabase\.co", base_url)
    if not match or not service_key:
        pytest.fail("Test Supabase URL/key missing or URL is not a canonical project URL")
    project_ref = match.group(1)
    if project_ref == PRODUCTION_PROJECT_REF or project_ref not in allowlist:
        pytest.fail("Supabase project is not explicitly allowlisted as an isolated test project")
    if len(service_key) < 20:
        pytest.fail("Test service key is implausibly short")
    return base_url, service_key


def _request(base_url, key, method, path, *, params=None, body=None, prefer=None):
    url = f"{base_url}/rest/v1/{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    data = None if body is None else json.dumps(body, allow_nan=False).encode()
    headers = {
        "apikey": key,
        "Authorization": f"Bearer {key}",
        "Content-Type": "application/json",
        "Accept": "application/json",
    }
    if prefer:
        headers["Prefer"] = prefer
    request = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=8) as response:
            raw = response.read()
            return json.loads(raw.decode()) if raw.strip() else None
    except urllib.error.HTTPError as exc:
        raise AssertionError(f"isolated test Supabase request failed: HTTP {exc.code} on {path}") from None
    except Exception as exc:
        raise AssertionError(f"isolated test Supabase transport failed: {type(exc).__name__}") from None


def _insert_authorization(base_url, key, *, auth_id, fingerprint, run_id, event_id, expires_at):
    now = datetime.now(timezone.utc)
    row = {
        "authorization_id": auth_id,
        "operation_fingerprint": fingerprint,
        "domain": "trading",
        "operation_type": "place_order",
        "target": "TEST-EURUSD",
        "amount": "1.00",
        "currency": "USD",
        "run_id": run_id,
        "event_id": event_id,
        "evidence_id": "synthetic-test-evidence",
        "approved_by": "synthetic-test-human",
        "approved_at_utc": (now - timedelta(minutes=5)).isoformat(),
        "expires_at_utc": expires_at.isoformat(),
        "status": "approved",
    }
    inserted = _request(
        base_url, key, "POST", "verox_financial_authorizations",
        params={"on_conflict": "authorization_id"}, body=row,
        prefer="return=representation",
    )
    assert isinstance(inserted, list) and len(inserted) == 1
    return row


def _consume(base_url, key, row):
    return _request(
        base_url, key, "POST", "rpc/consume_human_financial_authorization",
        body={
            "p_authorization_id": row["authorization_id"],
            "p_operation_fingerprint": row["operation_fingerprint"],
            "p_run_id": row["run_id"],
            "p_event_id": row["event_id"],
            "p_action": row["operation_type"],
            "p_target": row["target"],
            "p_domain": row["domain"],
            "p_source": "verox_t1_t6_integration_test",
            "p_agent": "synthetic-test",
            "p_stage": "synthetic-test",
        },
    )


def _cleanup(base_url, key, row):
    # Clean only synthetic IDs generated by this test; never touch production.
    _request(
        base_url, key, "DELETE", "verox_financial_authorizations",
        params={"authorization_id": f"eq.{row['authorization_id']}"},
        prefer="return=minimal",
    )
    _request(
        base_url, key, "DELETE", "nexus_runtime_events",
        params={"run_id": f"eq.{row['run_id']}", "source": "eq.verox_t1_t6_integration_test"},
        prefer="return=minimal",
    )
    remaining = _request(
        base_url, key, "GET", "verox_financial_authorizations",
        params={"select": "authorization_id", "authorization_id": f"eq.{row['authorization_id']}", "limit": "2"},
    )
    assert remaining == []


def test_t3_real_rpc_persists_expiration_on_isolated_supabase():
    base_url, key = _isolated_supabase()
    auth_id = "synthetic-t3-" + uuid.uuid4().hex
    row = _insert_authorization(
        base_url, key, auth_id=auth_id, fingerprint="a" * 64,
        run_id="run-t3-" + uuid.uuid4().hex,
        event_id="evt-t3-" + uuid.uuid4().hex,
        expires_at=datetime.now(timezone.utc) - timedelta(minutes=1),
    )
    try:
        result = _consume(base_url, key, row)
        result_row = result[0] if isinstance(result, list) and result else {}
        assert result_row.get("consumed") is False
        assert result_row.get("reason") == "approval_expired"
        stored = _request(
            base_url, key, "GET", "verox_financial_authorizations",
            params={"select": "status,consumed_at_utc", "authorization_id": f"eq.{auth_id}", "limit": "2"},
        )
        assert len(stored) == 1
        assert stored[0]["status"] == "expired"
        assert stored[0]["consumed_at_utc"] is None
    finally:
        _cleanup(base_url, key, row)


def test_t5_real_rpc_allows_exactly_one_concurrent_consumer():
    base_url, key = _isolated_supabase()
    auth_id = "synthetic-t5-" + uuid.uuid4().hex
    row = _insert_authorization(
        base_url, key, auth_id=auth_id, fingerprint="b" * 64,
        run_id="run-t5-" + uuid.uuid4().hex,
        event_id="evt-t5-" + uuid.uuid4().hex,
        expires_at=datetime.now(timezone.utc) + timedelta(minutes=5),
    )
    try:
        with concurrent.futures.ThreadPoolExecutor(max_workers=5) as pool:
            results = list(pool.map(lambda _: _consume(base_url, key, row), range(5)))
        rows = [result[0] if isinstance(result, list) and result else {} for result in results]
        assert sum(item.get("consumed") is True for item in rows) == 1
        assert sum(item.get("consumed") is False for item in rows) == 4
        stored = _request(
            base_url, key, "GET", "verox_financial_authorizations",
            params={"select": "status,consumed_at_utc,consumed_by_run_id,consumed_by_event_id",
                    "authorization_id": f"eq.{auth_id}", "limit": "2"},
        )
        assert len(stored) == 1
        assert stored[0]["status"] == "consumed"
        assert stored[0]["consumed_at_utc"]
        assert stored[0]["consumed_by_run_id"] == row["run_id"]
        assert stored[0]["consumed_by_event_id"] == row["event_id"]
        audits = _request(
            base_url, key, "GET", "nexus_runtime_events",
            params={"select": "event_id,status,source", "run_id": f"eq.{row['run_id']}",
                    "source": "eq.verox_t1_t6_integration_test", "status": "eq.authorized", "limit": "10"},
        )
        assert isinstance(audits, list) and len(audits) == 1
    finally:
        _cleanup(base_url, key, row)
